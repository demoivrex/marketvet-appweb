  actualizarArregloObjetivos(valCant: number, valKg: number, valVent: number, vendedor: string, mesGuardado: string, anioGuardado: string) {
    let indice: number;
    for (let i = 0; i < this.objetivosMes2.length; i++) {
      if (this.objetivosMes2[i].vendedor === vendedor) {
        indice = i;
        this.objetivosMes2[i].cantobj = valCant;
        this.objetivosMes2[i].kgobj = valKg;
        this.objetivosMes2[i].ventasobj = valVent;
        break;
      }
    }

    this.objetivosMes1[indice].cantobj = valCant * 0.95;
    this.objetivosMes1[indice].kgobj = valKg * 0.95;
    this.objetivosMes1[indice].ventasobj = valVent * 0.95;

    this.objetivosMes3[indice].cantobj = valCant * 1.05;
    this.objetivosMes3[indice].kgobj = valKg * 1.05;
    this.objetivosMes3[indice].ventasobj = valVent * 1.05;

    this.generarSumatoriaObjetivos(mesGuardado, anioGuardado);

    this.fb.actualizarObjetivos(this.objetivosMes2, mesGuardado, anioGuardado).subscribe();
    this.fb.actualizarObjetivos(this.objetivosMes1, (Number(mesGuardado) - 1).toString().padStart(2, '0'), anioGuardado).subscribe();
    this.fb.actualizarObjetivos(this.objetivosMes3, (Number(mesGuardado) + 1).toString().padStart(2, '0'), anioGuardado).subscribe();

    this.fb.actualizarObjetivosEspeciales(this.objetivosEspeciales, mesGuardado, anioGuardado).subscribe();
    this.fb.actualizarObjetivosEspeciales(this.objetivosEspeciales, (Number(mesGuardado) - 1).toString().padStart(2, '0'), anioGuardado).subscribe();
    this.fb.actualizarObjetivosEspeciales(this.objetivosEspeciales, (Number(mesGuardado) + 1).toString().padStart(2, '0'), anioGuardado).subscribe();
  }

  generarSumatoriaObjetivos(mesGuardado: string, anioGuardado: string) {
    this.variablesMap = {
      0: this.objetivosMes1,
      1: this.objetivosMes2,
      2: this.objetivosMes3,
    };
    for (let mes = 0; mes < 3; mes++) {
      let objVentasTrad = 0;
      let objCantTrad = 0;
      let objKgTrad = 0;
      let objArfvTrad = 0;
      let objArfcTrad = 0;
      let objVentasDist = 0;
      let objCantDist = 0;
      let objKgDist = 0;
      let objArfvDist = 0;
      let objArfcDist = 0;
      let cantDias;
      for (let i = 0; i < this.variablesMap[mes].length; i++) {
        if (this.variablesMap[mes][i].canal == 'tradicional') {
          objVentasTrad += this.variablesMap[mes][i].ventasobj;
          objCantTrad += this.variablesMap[mes][i].cantobj;
          objKgTrad += this.variablesMap[mes][i].kgobj;
          objArfvTrad += this.variablesMap[mes][i].arfvobj;
          objArfcTrad += this.variablesMap[mes][i].arfcobj;
        }
        if (this.variablesMap[mes][i].canal == 'distribuidores') {
          objVentasDist += this.variablesMap[mes][i].ventasobj;
          objCantDist += this.variablesMap[mes][i].cantobj;
          objKgDist += this.variablesMap[mes][i].kgobj;
          objArfvDist += this.variablesMap[mes][i].arfvobj;
          objArfcDist += this.variablesMap[mes][i].arfcobj;
        }
      }

      //Actualizo valores de ventas totales objetivo de SW y CI
      this.variablesMap[mes][8].ventastotalesobj = objVentasTrad;
      this.variablesMap[mes][5].ventastotalesobj = objVentasDist;

      cantDias = this.utilidades.obtenerDiasMesPorAno(Number(anioGuardado), (Number(mesGuardado) + (mes - 1)))
      let arraySumatoria: sumatoria[] = [];
      let actualizacion: boolean = false;

      this.fb.cargarSumatorias((Number(mesGuardado) + (mes - 1)).toString().padStart(2, '0'), anioGuardado).subscribe((resp: sumatoria[]) => {
        if (resp) {
          arraySumatoria = resp;
          actualizacion = true;
        }
        for (let i = 0; i <= cantDias; i++) {
          if (actualizacion) {
            arraySumatoria[i].objventastrad = objVentasTrad / cantDias * i;
            arraySumatoria[i].objventasdist = objVentasDist / cantDias * i;
            arraySumatoria[i].objcanttrad = objCantTrad / cantDias * i;
            arraySumatoria[i].objcantdist = objCantDist / cantDias * i;
            arraySumatoria[i].objkgtrad = objKgTrad / cantDias * i;
            arraySumatoria[i].objkgdist = objKgDist / cantDias * i;
            arraySumatoria[i].objarfctrad = objArfcTrad / cantDias * i;
            arraySumatoria[i].objarfcdist = objArfcDist / cantDias * i;
            arraySumatoria[i].objarfvtrad = objArfvTrad / cantDias * i;
            arraySumatoria[i].objarfvdist = objArfvDist / cantDias * i;
          }
          else {
            let sumatoriaTemp = new sumatoria();
            sumatoriaTemp.objventastrad = objVentasTrad / cantDias * i;
            sumatoriaTemp.objventasdist = objVentasDist / cantDias * i;
            sumatoriaTemp.objcanttrad = objCantTrad / cantDias * i;
            sumatoriaTemp.objcantdist = objCantDist / cantDias * i;
            sumatoriaTemp.objkgtrad = objKgTrad / cantDias * i;
            sumatoriaTemp.objkgdist = objKgDist / cantDias * i;
            sumatoriaTemp.objarfctrad = objArfcTrad / cantDias * i;
            sumatoriaTemp.objarfcdist = objArfcDist / cantDias * i;
            sumatoriaTemp.objarfvtrad = objArfvTrad / cantDias * i;
            sumatoriaTemp.objarfvdist = objArfvDist / cantDias * i;
            arraySumatoria.push(sumatoriaTemp);
          }
        }
        this.fb.actualizarSumatorias(arraySumatoria, (Number(mesGuardado) + (mes - 1)).toString().padStart(2, '0'), anioGuardado).subscribe();
      });
    }
  }

